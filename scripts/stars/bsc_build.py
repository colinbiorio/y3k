"""The night sky's stars for the frequencies room: the naked-eye part of the Yale
Bright Star Catalogue, written out as a small JavaScript module.

    python3 -I scripts/stars/bsc_build.py <heasarc_bsc5p.tdat.gz> src/frequencies/bsc.js

The input is NASA HEASARC's copy of the catalogue (table bsc5p: Hoffleit and Warren,
The Bright Star Catalogue, 5th revised edition, 1991), as its TDAT file
(https://heasarc.gsfc.nasa.gov/FTP/heasarc/dbase/tdat_files/heasarc_bsc5p.tdat.gz).
Every star brighter than V = 6.0 is kept (what the eye finds under a dark sky): its
J2000 place, its V magnitude, its B-V colour, and its proper motion where that moves it
more than a tenth of a degree in five thousand years. Packed as bytes (base64), decoded
by night.mjs's decodeStars. The same input gives the same output, byte for byte.
"""
import base64
import gzip
import struct
import sys

LIMIT = 6.0
NAMED = {          # HR number -> the name the room gives it
    5291: 'thuban', 424: 'polaris', 2491: 'sirius', 2326: 'canopus', 1903: 'alnilam', 1948: 'alnitak', 1852: 'mintaka',
    1165: 'alcyone', 1457: 'aldebaran', 1708: 'capella', 1713: 'rigel', 2061: 'betelgeuse', 7001: 'vega', 7924: 'deneb',
    7557: 'altair', 5340: 'arcturus', 8728: 'fomalhaut', 5563: 'kochab',
}


def main(src, out):
    with gzip.open(src, 'rt', encoding='latin-1') as f:
        lines = f.read().splitlines()
    cols = next(l for l in lines if l.startswith('line[1]')).split('=', 1)[1].split()
    ix = {c: i for i, c in enumerate(cols)}
    start = next(i for i, l in enumerate(lines) if l.startswith('<DATA>')) + 1
    stars = []
    for l in lines[start:]:
        if not l or l.startswith('<END>'):
            continue
        r = l.split('|')
        v = r[ix['vmag']].strip()
        if not v or float(v) >= LIMIT:
            continue
        ra, dec = float(r[ix['ra']]), float(r[ix['dec']])
        bv = r[ix['bv_color']].strip()
        pa, pd = r[ix['pmra']].strip(), r[ix['pmdec']].strip()
        pa = round(float(pa) * 1000) if pa else 0          # mas/yr, along the great circle (mu-alpha times cos delta)
        pd = round(float(pd) * 1000) if pd else 0
        if (pa * pa + pd * pd) ** 0.5 < 72:                # under 0.1 deg in 5000 years (72 mas a year): left out
            pa = pd = 0
        hr = int(r[ix['hr']])
        assert 0 <= ra < 360 and -90 <= dec <= 90, hr
        stars.append((hr, ra, dec, float(v), float(bv) if bv else 0.6, pa, pd))
    stars.sort(key=lambda s: (s[3], s[0]))                 # brightest first
    named = {NAMED[s[0]]: i for i, s in enumerate(stars) if s[0] in NAMED}
    assert len(named) == len(NAMED), sorted(set(NAMED.values()) - set(named))
    # six bytes a star: right ascension (a 65536th of a turn), declination (a 32767th of 90 degrees),
    # V + 2 in 30ths of a magnitude, B-V in 60ths; then, for the few that move, six more: which, and how
    packed = b''.join(struct.pack('<HhBb', round(s[1] / 360 * 65536) % 65536, round(s[2] / 90 * 32767),
                                  round((s[3] + 2) * 30), max(-127, min(127, round(s[4] * 60)))) for s in stars)
    moving = b''.join(struct.pack('<Hhh', i, s[5], s[6]) for i, s in enumerate(stars) if s[5] or s[6])
    wrap = lambda b: "'" + "' +\n  '".join(base64.b64encode(b).decode()[i:i + 120] for i in range(0, len(base64.b64encode(b)), 120)) + "'"
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// GENERATED by scripts/stars/bsc_build.py from the Yale Bright Star Catalogue, 5th revised edition\n')
        f.write('// (Hoffleit and Warren, 1991; NASA HEASARC table bsc5p). Do not edit: run the script again.\n')
        f.write('//\n// Every star brighter than V = %.1f, brightest first, packed six bytes each (little-endian): right\n' % LIMIT)
        f.write('// ascension in 65536ths of a turn and declination in 32767ths of 90 degrees (J2000), V + 2 in 30ths of\n')
        f.write('// a magnitude, B-V in 60ths (0.6 where the catalogue has none). MOVING: for the stars whose proper\n')
        f.write('// motion moves them more than a tenth of a degree in five thousand years, six bytes each: the star,\n')
        f.write('// then its motion along the great circle in right ascension and in declination (mas a year).\n')
        f.write('// Decoded by night.mjs (decodeStars).\n')
        f.write('export const COUNT = %d;\n' % len(stars))
        f.write('export const NAMED = { %s };\n' % ', '.join('%s: %d' % (k, named[k]) for k in sorted(named)))
        f.write('export const PACKED =\n  %s;\n' % wrap(packed))
        f.write('export const MOVING =\n  %s;\n' % wrap(moving))
    print(len(stars), 'stars ->', out)


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
